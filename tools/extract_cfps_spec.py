#!/usr/bin/env python3
"""
Extract the canonical CFPSReagentList contract + costs from the autonomous-cfps
pydantic model and print it as JSON on stdout.

This is the SINGLE extraction point that keeps ginkgo-artworks in step with
ginkgobioworks/autonomous-cfps. It imports the real model (introspection, no
source-parsing) so it can't silently drift from what the Python actually enforces.

Run it inside the autonomous-cfps environment, e.g.:

    uv run --project ../autonomous-cfps python tools/extract_cfps_spec.py

It is normally invoked by tools/sync-cfps.mjs, which writes the committed
src/lib/cfpsReagentSpec.generated.json (the contract the app validates against)
and pushes the per-reagent costs to the live PocketBase reagent-groups record.
"""

import json
import os
import subprocess
import sys
from datetime import datetime, timezone

try:
    from autonomous_cfps.models import (
        CFPSReagentList,
        TEMPLATE_FIELDS,
        TEMPLATE_VOLUME,
        TEMPLATE_TO_PROTEIN_TARGET,
    )
except Exception as exc:  # pragma: no cover - environment guard
    sys.stderr.write(f"Failed to import autonomous_cfps.models: {exc!r}\n")
    sys.stderr.write(
        "Run inside the autonomous-cfps env, e.g. "
        "`uv run --project <path-to-autonomous-cfps> python tools/extract_cfps_spec.py`.\n"
    )
    raise SystemExit(1)

# The 25 nL Echo dispense grid and the fixed 20 µL reaction total are enforced in
# the model by validators (the `% 25` increment assertion and validate_total_volume),
# not exposed as importable constants -- mirror them here. If those validators ever
# change upstream, update these two lines; the sync diff will surface it in review.
STEP_NL = 25
MAX_TOTAL_NL = 20000


def source_commit() -> str | None:
    """Best-effort git SHA of the autonomous_cfps package's own checkout."""
    try:
        import autonomous_cfps

        pkg_dir = os.path.dirname(os.path.abspath(autonomous_cfps.__file__))
        sha = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=pkg_dir,
            stderr=subprocess.DEVNULL,
        )
        return sha.decode().strip()
    except Exception:
        return None


def build_spec() -> dict:
    fields: dict[str, dict] = {}
    for name, field_info in CFPSReagentList.model_fields.items():
        if getattr(field_info, "exclude", False):
            continue
        extra = getattr(field_info, "json_schema_extra", None) or {}
        fields[name] = {
            "default": field_info.default,
            "cost": extra.get("cost"),
            "cost_ginkgo": extra.get("cost_ginkgo"),
            "out_of_stock": bool(extra.get("out_of_stock", False)),
        }

    # base_buffer and lysate are fixed by their non-zero model defaults.
    base_buffer_default = fields.get("base_buffer", {}).get("default")
    lysate_default = fields.get("lysate", {}).get("default")

    return {
        "_comment": (
            "GENERATED by tools/extract_cfps_spec.py from the autonomous-cfps "
            "pydantic model. Do not edit by hand -- run `npm run sync:cfps` to "
            "regenerate. Source of truth: ginkgobioworks/autonomous-cfps."
        ),
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "sourceRepo": "ginkgobioworks/autonomous-cfps",
        "sourceCommit": source_commit(),
        "stepNl": STEP_NL,
        "maxTotalNl": MAX_TOTAL_NL,
        "templateFields": list(TEMPLATE_FIELDS),
        "templateVolumeNl": int(TEMPLATE_VOLUME),
        "baseBufferNl": int(base_buffer_default) if base_buffer_default is not None else None,
        "lysateNl": int(lysate_default) if lysate_default is not None else None,
        "templateToProteinTarget": {
            key: str(target.value) for key, target in TEMPLATE_TO_PROTEIN_TARGET.items()
        },
        "fieldCount": len(fields),
        "fields": fields,
    }


def main() -> None:
    json.dump(build_spec(), sys.stdout, indent=2, default=str, sort_keys=True)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
